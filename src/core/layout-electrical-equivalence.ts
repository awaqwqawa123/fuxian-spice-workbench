import { dcSweep, type Project } from './circuit'
import { compileDrawing, terminalKey } from './drawing'
import { pinsFor } from './devices'

export interface LayoutElectricalDifference { path: string; before: unknown; after: unknown }
const stable = (value: unknown): string => JSON.stringify(value, (_key, item) => item && typeof item === 'object' && !Array.isArray(item)
  ? Object.fromEntries(Object.entries(item).sort(([a], [b]) => a.localeCompare(b))) : item) ?? 'undefined'

/**
 * Electrical invariants for a layout-only proposal. Intermediate junctions and
 * conductor IDs are not electrical nodes: compare partitions of real pin IDs.
 * This intentionally does not replace the simulation/cache key or migrate probes.
 */
function invariants(project: Project): Record<string, unknown> {
  const fields: Record<string, unknown> = {}
  for (const name of ['schemaVersion', 'template', 'analysis', 'source', 'values', 'ac', 'tran'] as const) fields[`project.${name}`] = project[name]
  fields['project.dc'] = dcSweep(project)
  fields['project.temperature'] = project.temperature ?? 27
  fields['project.sweep'] = project.sweep
  fields['project.solver'] = project.solver
  fields['project.noise.summaryInterval'] = project.noise?.summaryInterval ?? 0
  for (const model of project.models ?? []) fields[`project.models[${model.id}]`] = model
  const drawing = project.drawing
  fields['project.drawing.present'] = !!drawing
  if (!drawing) {
    fields['project.noise.negative'] = project.noise?.negative ?? null
    fields['project.initialConditions'] = project.initialConditions ?? []
    fields['project.nodeSets'] = project.nodeSets ?? []
    return fields
  }
  fields['project.drawing.sourceId'] = drawing.sourceId
  // A probe attachment is an identity-bearing reference. Do not silently move
  // the designated output to another terminal, even if both share a net.
  fields['project.drawing.output'] = drawing.output
  const topology = compileDrawing(drawing), groups = new Map<string, string[]>()
  const add = (net: string, member: string) => groups.set(net, [...(groups.get(net) ?? []), member])
  for (const device of drawing.devices) {
    fields[`project.drawing.devices[${device.id}]`] = { kind: device.kind, value: device.value, params: device.params ?? {},...(device.kind==='X'?{pins:device.pins}: {}) }
    for (const pin of pinsFor(device)) add(topology.nodes.get(`${device.id}:${pin}`)!, `${device.id}:${pin}`)
  }
  // Explicit names participate in the partition; autogenerated n1/n2 etc. do
  // not. This also protects named nets which currently contain no device pin.
  for (const label of drawing.labels ?? []) add(topology.nodes.get(terminalKey(label.at))!, `label:${label.name}`)
  for (const members of groups.values()) members.sort()
  const network = (key: string) => groups.get(topology.nodes.get(key)!) ?? []
  // Condition terminals have electrical identity. Junction IDs can change in a
  // pure reroute; physical pin IDs remain protected, as do their true networks.
  const settingTarget = (at: import('./drawing').Terminal) => {
    const key=terminalKey(at),node=topology.nodes.get(key)
    return { ...('device' in at || node===undefined ? {terminal:key}:{}), network:node===undefined?null:network(key) }
  }
  fields['project.noise.negative'] = project.noise?.negative?settingTarget(project.noise.negative):null
  for(const field of ['initialConditions','nodeSets'] as const)fields[`project.${field}`]=(project[field]??[]).map(item=>({at:settingTarget(item.at),value:item.value})).sort((a,b)=>stable(a).localeCompare(stable(b)))
  for (const device of drawing.devices) for (const pin of pinsFor(device)) {
    const key = `${device.id}:${pin}`
    fields[`project.drawing.pins[${key}].network`] = network(key)
  }
  for (const label of drawing.labels ?? []) fields[`project.drawing.labels[${label.id}]`] = { name: label.name, network: network(terminalKey(label.at)) }
  if (drawing.output) fields['project.drawing.output.network'] = network(terminalKey(drawing.output))
  return fields
}

export function layoutElectricalDifferences(before: Project, after: Project): LayoutElectricalDifference[] {
  const result: LayoutElectricalDifference[] = []
  function compare(path: string, a: unknown, b: unknown) {
    if (stable(a) === stable(b)) return
    if (a && b && typeof a === 'object' && typeof b === 'object' && !Array.isArray(a) && !Array.isArray(b)) {
      const left = a as Record<string, unknown>, right = b as Record<string, unknown>
      for (const key of [...new Set([...Object.keys(left), ...Object.keys(right)])].sort()) compare(`${path}.${key}`, left[key], right[key])
    } else result.push({ path, before: a, after: b })
  }
  const a = invariants(before), b = invariants(after)
  for (const path of [...new Set([...Object.keys(a), ...Object.keys(b)])].sort()) compare(path, a[path], b[path])
  return result
}

export const layoutElectricallyEquivalent = (before: Project, after: Project): boolean => layoutElectricalDifferences(before, after).length === 0

export function assertLayoutElectricalEquivalent(before: Project, after: Project): void {
  const differences = layoutElectricalDifferences(before, after)
  if (!differences.length) return
  const display = (value: unknown) => { const text = stable(value); return text.length > 320 ? `${text.slice(0, 317)}…` : text }
  const details = differences.slice(0, 8).map(item => `${item.path}: ${display(item.before)} → ${display(item.after)}`).join('；')
  throw new Error(`本轮只要求重排原理图，不能修改电气连接、器件参数或仿真配置。具体差异：${details}${differences.length > 8 ? `；另有 ${differences.length - 8} 项差异` : ''}`)
}
