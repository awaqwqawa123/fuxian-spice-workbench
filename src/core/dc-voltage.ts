import { newProject, type Project } from './circuit'
import { compileDrawing } from './drawing'
import { layoutElectricallyEquivalent } from './layout-electrical-equivalence'
import type { Result } from './results'

/** A separate bias calculation uses the saved DC source values, never a sweep sample. */
export function dcVoltageProject(project:Project):Project {
  // .ic constrains a transient startup (and may constrain the DC solve itself);
  // the bias meter must not inherit it. .nodeset is only a convergence seed and
  // intentionally selects the saved circuit's bias branch for multistable circuits.
  const {sweep:_sweep,waveformSetup:_setup,initialConditions:_initial,noise:_noise,...rest}=project
  const defaults=newProject()
  return {...rest,analysis:'op',ac:defaults.ac,tran:defaults.tran,dc:defaults.dc}
}

export function dcVoltageResultMatches(result:Result,project:Project):boolean {
  return result.analysis==='op'&&result.points===1&&!result.sweepResults?.length&&!result.project.sweep&&!result.experiment?.sweep
    &&layoutElectricallyEquivalent(dcVoltageProject(result.project),dcVoltageProject(project))
}

/** Match by terminal identity: autogenerated node names can change after a layout edit. */
export function dcNodeVoltages(result:Result,project:Project):Map<string,number> {
  const values=new Map<string,number>()
  if(!project.drawing||!result.project.drawing||!dcVoltageResultMatches(result,project))return values
  const before=compileDrawing(result.project.drawing).nodes,after=compileDrawing(project.drawing).nodes
  const vectors=new Map(Object.entries(result.voltages??{}).map(([name,samples])=>[name.toLowerCase(),samples]))
  for(const [terminal,node] of after){
    if(node==='0'){values.set(node,0);continue}
    const original=before.get(terminal)
    if(original===undefined)continue
    const samples=vectors.get(`v(${original.toLowerCase()})`)
    if(samples?.length===1&&Number.isFinite(samples[0]))values.set(node,samples[0])
  }
  return values
}
